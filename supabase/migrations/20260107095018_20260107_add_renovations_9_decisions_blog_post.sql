<h2>1) Définir le vrai objectif de vos rénovations</h2>

<p>Avant de parler "travaux", clarifiez l''intention :</p>

<ul>
<li>Confort : mieux chauffer, mieux ventiler, réduire le bruit</li>
<li>Fonction : ouvrir une cuisine, créer un bureau, gagner du rangement</li>
