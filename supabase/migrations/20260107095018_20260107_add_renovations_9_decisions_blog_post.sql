<ul>
<li>Ai-je un objectif clair (confort / esthétique / énergie / conformité) ?</li>
<li>Le périmètre est-il défini pièce par pièce ?</li>
<li>Les problèmes de fond (humidité/ventilation) sont-ils traités en priorité ?</li>
<li>Le budget inclut-il les finitions et une marge imprévus ?</li>
<li>L''ordre des travaux est-il logique (réseaux avant peinture) ?</li>
<li>La coordination du chantier est-elle prévue (qui pilote quoi) ?</li>
</ul>

